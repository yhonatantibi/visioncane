import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

function replaceOnce(text, before, after, marker) {
  if (text.includes(marker)) return text;
  if (text.split(before).length !== 2) throw new Error(`Pinned plugin changed: ${marker}`);
  return text.replace(before, after);
}

export function patchAndroid(text) {
  text = replaceOnce(text,
    'result.copy(originalImage = bitmap)  // Reuse bitmap from ImageProxy conversion',
    `// VisionCane: use the same camera rotation as the detector, never a guessed orientation.
                    val upright = android.graphics.Bitmap.createBitmap(
                        bitmap, 0, 0, bitmap.width, bitmap.height,
                        android.graphics.Matrix().apply { postRotate(rotationDegrees.toFloat()) }, true)
                    result.copy(originalImage = upright)`, 'VisionCane: use the same camera rotation');
  return replaceOnce(text,
    'enhancedStreamData["imageHeight"] = resultWithOriginalImage.origShape.height',
    `enhancedStreamData["imageHeight"] = resultWithOriginalImage.origShape.height
                        enhancedStreamData["visioncaneUprightImage"] =
                            resultWithOriginalImage.originalImage?.width == orientedWidth &&
                            resultWithOriginalImage.originalImage?.height == orientedHeight`,
    'enhancedStreamData["visioncaneUprightImage"]');
}

export function patchApple(text) {
  // UIKit draw applies UIImage.imageOrientation; JPEG now contains physically
  // upright pixels. Only attest alignment when dimensions agree with detections.
  text = replaceOnce(text,
    'if let imageData = originalImage.jpegData(compressionQuality: 0.9) {',
    `// VisionCane: bake UIImage orientation into the JPEG pixels.
        let format = UIGraphicsImageRendererFormat()
        format.scale = 1
        let renderer = UIGraphicsImageRenderer(size: originalImage.size, format: format)
        let upright = renderer.image { _ in originalImage.draw(at: .zero) }
        if let imageData = upright.jpegData(compressionQuality: 0.9) {`,
    'VisionCane: bake UIImage orientation');
  return replaceOnce(text,
    'map["originalImage"] = imageData',
    `map["originalImage"] = imageData
          map["visioncaneUprightImage"] =
            Int(upright.size.width) == Int(result.orig_shape.width) &&
            Int(upright.size.height) == Int(result.orig_shape.height)`,
    'map["visioncaneUprightImage"]');
}

export function preparePlugin(root) {
  const configPath = path.join(root, '.dart_tool/package_config.json');
  const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const pkg = config.packages.find(p => p.name === 'ultralytics_yolo');
  if (!pkg) throw new Error('Run pub get before preparing the pinned plugin.');
  const source = fileURLToPath(new URL(pkg.rootUri, pathToFileURL(configPath)));
  if (!/^version:\s*0\.6\.16\s*$/m.test(fs.readFileSync(path.join(source, 'pubspec.yaml'), 'utf8'))) {
    throw new Error('Native patch requires ultralytics_yolo 0.6.16.');
  }
  // Keep the shared pub cache pristine. This build owns only its private copy.
  const dest = path.join(root, '.visioncane/ultralytics_yolo');
  const overridesPath = path.join(root, 'pubspec_overrides.yaml');
  const override = '# Generated by tool/prepare_plugin.mjs\ndependency_overrides:\n  ultralytics_yolo:\n    path: .visioncane/ultralytics_yolo\n';
  if (fs.existsSync(overridesPath) && fs.readFileSync(overridesPath, 'utf8') !== override) {
    throw new Error('An existing user pubspec_overrides.yaml must be merged explicitly.');
  }
  if (path.resolve(source) !== path.resolve(dest)) {
    fs.mkdirSync(dest, {recursive:true});
    for (const name of ['lib', 'android', 'ios', 'pubspec.yaml', 'LICENSE']) {
      fs.cpSync(path.join(source, name), path.join(dest, name), {recursive:true});
    }
  }
  for (const [relative, patch] of [
    ['android/src/main/kotlin/com/ultralytics/yolo/YOLOView.kt', patchAndroid],
    ['ios/ultralytics_yolo/Sources/ultralytics_yolo/YOLOView.swift', patchApple],
  ]) {
    const file = path.join(dest, relative);
    fs.writeFileSync(file, patch(fs.readFileSync(file, 'utf8')));
  }
  fs.writeFileSync(overridesPath, override);
  console.log('Private camera plugin patched for aligned same-frame pixels. Run pub get again.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  preparePlugin(fileURLToPath(new URL('../', import.meta.url)));
}
